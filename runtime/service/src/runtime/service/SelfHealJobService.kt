package com.github.yumeyucca.yumebox.runtime.service

import android.app.job.JobParameters
import android.app.job.JobService
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.cancel
import kotlinx.coroutines.launch

/**
 * The periodic half of [SelfHeal]. It survives a SIGKILL of the app process, so it also starts a
 * process that nothing else would; a force stop cancels it with every other job of the app.
 */
class SelfHealJobService : JobService() {
    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.Default)

    override fun onStartJob(params: JobParameters): Boolean {
        scope.launch {
            try {
                SelfHeal.restoreIfNeeded(applicationContext, SelfHeal.TRIGGER_WATCHDOG)
            } finally {
                jobFinished(params, false)
            }
        }
        return true
    }

    override fun onStopJob(params: JobParameters): Boolean = false

    override fun onDestroy() {
        scope.cancel()
        super.onDestroy()
    }
}
